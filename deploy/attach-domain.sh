#!/usr/bin/env bash
# Wire a real domain onto an already-installed Shahrah exit + (optional) panel.
# Does NOT talk to Cloudflare/DNS APIs — prints the exact DNS/TLS steps for the operator.
#
# Usage (on the foreign exit, as root):
#   ./deploy/attach-domain.sh \
#     --edge edge.example.com \
#     --panel panel.example.com \
#     --sub sub.example.com \
#     --state /var/lib/shahrah/state.json
#
# Never commit the real hostnames you pass here.

set -euo pipefail

EDGE=""
PANEL=""
SUB=""
STATE="${SHAHRAH_STATE:-/var/lib/shahrah/state.json}"
ORIGIN_PORT=8080
APPLY=0
XRAY_BIN="${SHAHRAH_XRAY_BIN:-/usr/local/bin/xray}"

usage() {
  sed -n '2,12p' "$0" | sed 's/^# \?//'
  exit "${1:-0}"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --edge) EDGE="${2:-}"; shift 2 ;;
    --panel) PANEL="${2:-}"; shift 2 ;;
    --sub) SUB="${2:-}"; shift 2 ;;
    --state) STATE="${2:-}"; shift 2 ;;
    --origin-port) ORIGIN_PORT="${2:-}"; shift 2 ;;
    --apply) APPLY=1; shift ;;
    -h|--help) usage 0 ;;
    *) echo "unknown arg: $1" >&2; usage 2 ;;
  esac
done

if [[ -z "$EDGE" ]]; then
  echo "error: --edge HOST is required (CDN client hostname)" >&2
  usage 2
fi
if [[ ! "$EDGE" =~ ^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$ ]]; then
  echo "error: --edge looks invalid: $EDGE" >&2
  exit 2
fi
if [[ ! -f "$STATE" ]]; then
  echo "error: state file missing: $STATE (run install.sh first)" >&2
  exit 2
fi

PATH_SECRET="$(openssl rand -hex 24)"
CADDY_OUT="/etc/caddy/Caddyfile.shahrah"
mkdir -p "$(dirname "$CADDY_OUT")"

{
  echo "# Generated by attach-domain.sh — replace only via re-run; do not commit."
  if [[ -n "$PANEL" ]]; then
    cat <<EOF
$PANEL {
	reverse_proxy 127.0.0.1:8000
}
EOF
  fi
  if [[ -n "$SUB" ]]; then
    cat <<EOF
$SUB {
	reverse_proxy 127.0.0.1:8788
}
EOF
  fi
  cat <<EOF
$EDGE {
	reverse_proxy 127.0.0.1:${ORIGIN_PORT}
}
EOF
} >"$CADDY_OUT"

echo "== Shahrah domain attach plan =="
echo "state:        $STATE"
echo "CDN edge:     $EDGE"
echo "origin port:  $ORIGIN_PORT (cdn-xhttp, plain HTTP behind edge TLS)"
echo "XHTTP path:   /$PATH_SECRET   (treat as a credential)"
echo "Caddyfile:    $CADDY_OUT"
[[ -n "$PANEL" ]] && echo "panel host:   $PANEL"
[[ -n "$SUB" ]] && echo "sub host:     $SUB"
echo
echo "== DNS (Cloudflare) =="
echo "1. Add A/AAAA for $EDGE -> this exit's public IP (orange-cloud ON for CDN hide)."
[[ -n "$PANEL" ]] && echo "2. Add A/AAAA for $PANEL -> panel VPS (or same exit); orange-cloud optional."
[[ -n "$SUB" ]] && echo "3. Add A/AAAA for $SUB -> host running serve-sub."
echo "4. SSL/TLS mode: Full (strict once origin has a cert; Full is fine with Caddy on origin)."
echo "5. Disable Rocket Loader, email obfuscation, HTML minify for $EDGE."
echo
echo "== Local Xray listener =="
SPEC="${ORIGIN_PORT}:cdn-xhttp:${EDGE}:/${PATH_SECRET}"
echo "  shahrah --state $STATE listener add $SPEC"
echo "  shahrah --state $STATE apply --xray-bin $XRAY_BIN --config-out /etc/shahrah/xray.json"
if [[ "$APPLY" -eq 1 ]]; then
  shahrah --state "$STATE" listener add "$SPEC"
  shahrah --state "$STATE" apply --xray-bin "$XRAY_BIN" \
    --config-out /etc/shahrah/xray.json
  systemctl restart shahrah-xray
  echo "applied + restarted shahrah-xray"
else
  echo "(dry-run) re-run with --apply to mutate state and restart Xray"
fi
echo
echo "== After DNS propagates =="
echo "  caddy validate --config $CADDY_OUT && systemctl reload caddy"
echo "  shahrah panel provision --update-core   # subscriptions advertise $EDGE"
echo "  From Iran: import sub, prefer CDN host; confirm origin IP is not dialed by the client."
echo
SECRET_FILE=/var/lib/shahrah/cdn-path.secret
echo "Path secret also written to: $SECRET_FILE"
umask 077
mkdir -p /var/lib/shahrah
printf '%s\n' "/$PATH_SECRET" >"$SECRET_FILE"
chmod 600 "$SECRET_FILE"
